"""Generates everything the assembler includes: build/*.bin and build/gen.asm."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import tiles, rooms, sprites, font, title, music

OUT = sys.argv[1] if len(sys.argv) > 1 else "build"

def asm_bytes(label, values, per=20):
    lines = [f"{label}:"] if label else []
    values = list(values)
    for i in range(0, len(values), per):
        lines.append("  !byte " + ",".join(str(v & 255) for v in values[i:i + per]))
    if not values:
        lines.append("  ; (empty)")
    return "\n".join(lines) + "\n"

def write(name, data):
    with open(os.path.join(OUT, name), "wb") as f:
        f.write(data)

asm = ["; GENERATED by tools/build_assets.py - do not edit\n"]

# --- charsets: outdoor rooms use charset B, indoor rooms charset A
names = list(rooms.ROOMS)
groups = {True: [], False: []}
for n in names:
    groups[rooms.ROOMS[n]["lit"]].append(n)
tile_tl, tile_tr, tile_bl, tile_br, tile_flags, tile_col = [], [], [], [], [], []
tile_index = {}
codes_by_group = {}
for lit, group in groups.items():
    syms = sorted({c for n in group for row in rooms.ROOMS[n]["map"] for c in row})
    codes, data, count = tiles.build_charset(syms)
    write("charset_out.bin" if lit else "charset_in.bin", data)
    codes_by_group[lit] = codes
    print(f"charset {'outdoor' if lit else 'indoor '}: {count}/128 chars, {len(syms)} tiles")
    for s in syms:
        tile_index[(lit, s)] = len(tile_tl)
        tl, tr, bl, br = codes[s]
        tile_tl.append(tl); tile_tr.append(tr); tile_bl.append(bl); tile_br.append(br)
        tile_flags.append(tiles.TILES[s][0]); tile_col.append(tiles.TILES[s][1] | 8)
assert len(tile_tl) < 256
for n, v in (("tile_tl", tile_tl), ("tile_tr", tile_tr), ("tile_bl", tile_bl), ("tile_br", tile_br),
             ("tile_flags", tile_flags), ("tile_col", tile_col)):
    asm.append(asm_bytes(n, v))
rain = codes_by_group[True]["~"]
asm.append(f"RAIN_TL = {rain[0]}\nRAIN_TR = {rain[1]}\nRAIN_BL = {rain[2]}\nRAIN_BR = {rain[3]}\n")
asm.append(f"TF_SOLID = {tiles.SOLID}\nTF_PLATFORM = {tiles.PLATFORM}\nTF_LADDER = {tiles.LADDER}\nTF_CLOCK = {tiles.CLOCK}\n")

# --- rooms
idx = {n: i for i, n in enumerate(names)}
maps = bytearray()
for n in names:
    r = rooms.ROOMS[n]
    for row in r["map"]:
        assert len(row) == 20, (n, row)
        for c in row:
            maps.append(tile_index[(r["lit"], c)])
write("rooms.bin", bytes(maps))
asm.append(f"NUM_ROOMS = {len(names)}\nSTART_ROOM = {idx[rooms.START_ROOM]}\nHALL_ROOM = {idx[rooms.HALL_ROOM]}\n")
for key, fn in (("room_d022", lambda r: r["pal"][0]), ("room_d023", lambda r: r["pal"][1]),
                ("room_dim", lambda r: r["pal"][2] | 8), ("room_lit", lambda r: 1 if r["lit"] else 0)):
    asm.append(asm_bytes(key, [fn(rooms.ROOMS[n]) for n in names]))
for side in "LRUD":
    asm.append(asm_bytes(f"room_exit_{side.lower()}", [idx[rooms.ROOMS[n]["exits"][side]] if side in rooms.ROOMS[n]["exits"] else 255 for n in names]))
asm.append(asm_bytes("room_item", [rooms.ROOMS[n]["item"][0] if rooms.ROOMS[n]["item"] else 255 for n in names]))
asm.append(asm_bytes("room_item_x", [rooms.ROOMS[n]["item"][1] * 16 - 4 if rooms.ROOMS[n]["item"] else 0 for n in names]))
asm.append(asm_bytes("room_item_xh", [(rooms.ROOMS[n]["item"][1] * 16 - 4) >> 8 if rooms.ROOMS[n]["item"] else 0 for n in names]))
asm.append(asm_bytes("room_item_y", [rooms.ROOMS[n]["item"][2] * 16 - 2 if rooms.ROOMS[n]["item"] else 0 for n in names]))
brooke_room = next(n for n in names if any(e[0] == rooms.BROOKE for e in rooms.ROOMS[n]["enemies"]))
asm.append(f"BROOKE_ROOM = {idx[brooke_room]}\n")
for slot in range(2):
    es = [(rooms.ROOMS[n]["enemies"] + [None, None])[slot] for n in names]
    asm.append(asm_bytes(f"room_e{slot}_type", [e[0] if e else 255 for e in es]))
    asm.append(asm_bytes(f"room_e{slot}_x", [(e[1] * 16 if e else 0) & 255 for e in es]))
    asm.append(asm_bytes(f"room_e{slot}_xh", [(e[1] * 16 if e else 0) >> 8 for e in es]))
    asm.append(asm_bytes(f"room_e{slot}_y", [(e[2] * 16 - 5 if e else 0) & 255 for e in es]))
for n in names:
    asm.append(f"name_{idx[n]}: !scr \"{n.lower()}\",0\n")
asm.append("room_name_lo: !byte " + ",".join(f"<name_{i}" for i in range(len(names))) + "\n")
asm.append("room_name_hi: !byte " + ",".join(f">name_{i}" for i in range(len(names))) + "\n")

# --- light discs: half-width per |dy| for radius 0..8 (9 bytes per radius)
disc = []
for R in range(9):
    for dy in range(9):
        disc.append(0xFF if dy > R else int(((R + 0.45) ** 2 - dy * dy) ** 0.5))
asm.append(asm_bytes("disc_table", disc, 9))

# --- sprites
spr, const, _ = sprites.build()
assert len(spr) // 64 <= 128
write("sprites.bin", spr)
for k, v in const.items():
    asm.append(f"{k} = {v}\n")
print(f"sprites: {len(spr)//64}/128 frames")

# --- font, HUD codes
write("font.bin", font.build())
asm.append(f"H_GAUGE = {font.H_GAUGE}\nH_HEART = {font.H_HEART}\nH_HEART0 = {font.H_HEART0}\nH_ICON = {font.H_ICON}\nH_ICON0 = {font.H_ICON0}\nH_RULE = {font.H_RULE}\n")

# --- title picture
bm, scr, col, _, clashes = title.convert(title.draw())
write("title_bitmap.bin", bm); write("title_screen.bin", scr); write("title_color.bin", col)
asm.append(f"TITLE_BG = {title.BG}\n")
print("title clashes:", clashes)

# --- music
ft = music.freq_table()
asm.append(asm_bytes("freq_lo", [f & 255 for f in ft]))
asm.append(asm_bytes("freq_hi", [f >> 8 for f in ft]))
song_list = list(music.SONGS)
for s in song_list:
    so = music.SONGS[s]
    for v, data in enumerate(so["v"]):
        asm.append(asm_bytes(f"song_{s}_v{v}", data))
    asm.append(f"SONG_{s.upper()} = {song_list.index(s)}\n")
for v in range(3):
    lo = ",".join(f"<song_{s}_v{v}" if v < len(music.SONGS[s]["v"]) else "0" for s in song_list)
    hi = ",".join(f">song_{s}_v{v}" if v < len(music.SONGS[s]["v"]) else "0" for s in song_list)
    asm.append(f"song_ptr_lo_{v}: !byte {lo}\nsong_ptr_hi_{v}: !byte {hi}\n")
for key in ("wave", "ad", "sr", "arp"):
    flat = []
    for s in song_list:
        vals = music.SONGS[s][key] + [0] * 3
        flat += vals[:3]
    asm.append(asm_bytes(f"song_{key}", flat))

with open(os.path.join(OUT, "gen.asm"), "w") as f:
    f.write("".join(asm))
