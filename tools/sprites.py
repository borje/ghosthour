def norm(g):
    g = g.split() if isinstance(g, str) else list(g)
    out = []
    for r in g:
        assert len(r) <= 24, (len(r), r)
        out.append(r.ljust(24, "."))
    while len(out) < 21:
        out.append("." * 24)
    assert len(out) == 21, len(out)
    return out

def hires(g, ch):
    data = bytearray(64)
    for y, r in enumerate(g):
        for x, p in enumerate(r):
            if p in ch:
                data[y * 3 + x // 8] |= 0x80 >> (x % 8)
    return bytes(data)

MC_BITS = {"S": 1, "Y": 2, "W": 3}

def fill(g):
    """Multicolour layer: bit pair per 2 hi-res px. Ink pixels are backed by the nearest colour."""
    data = bytearray(64)
    for y, r in enumerate(g):
        for x in range(0, 24, 2):
            pair = [p for p in r[x:x + 2] if p in MC_BITS]
            if pair:
                v = MC_BITS[pair[0]]
                data[y * 3 + x // 8] |= v << (6 - (x % 8))
    return bytes(data)

def layers(g):
    g = norm(g)
    return hires(g, "K"), fill(g)

def build():
    """Returns (sprite_bytes, constants, previews)."""
    out = bytearray()
    const = {}
    previews = []

    def add(b):
        out.extend(b)
        return len(out) // 64 - 1

    # player: [facing][frame][ink,fill] 7 frames
    frames = [TOP + LEGS[k].split() for k in ("stand", "run1", "run2", "run3", "jump")] + [CLIMB1, CLIMB2]
    const["SP_PLAYER"] = 0
    for facing in range(2):
        for f in frames:
            g = norm(f)
            if facing:
                g = mirror_grid(g)
            ink, fl = layers(g)
            add(ink), add(fl)
            if not facing:
                previews.append(("player", g, 7))
    # enemies: [dir][anim][ink,fill]
    for name, a, b, col in (("GHOST", GHOST1, GHOST2, 15), ("BAT", BAT1, BAT2, 11), ("WOLF", WOLF1, WOLF2, 9), ("BROOKE", BROOKE1, BROOKE2, 7)):
        const["SP_" + name] = len(out) // 64
        for facing in range(2):
            for f in (a, b):
                g = norm(f)
                if facing:
                    g = mirror_grid(g)
                ink, fl = layers(g)
                add(ink), add(fl)
                if not facing:
                    previews.append((name, g, col))
    const["SP_EYES"] = len(out) // 64
    for e in (EYES_G, EYES_B, EYES_W):
        add(fill(norm(e)))
    const["SP_FLAME"] = len(out) // 64
    for f in FLAME:
        g = norm(f)
        add(fill(g))
        previews.append(("flame", g, 7))
    const["SP_ITEM"] = len(out) // 64
    for k in ("cog", "spring", "pendulum", "key", "candle", "glint"):
        g = norm(ITEMS[k])
        add(hires(g, "#"))
        previews.append((k, [r.replace("#", "W") for r in g], 1))
    return bytes(out), const, previews
